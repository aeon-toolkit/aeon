def test_catch22_names_cover_all_features():
    """Test that the name list covers every Catch22 feature."""
    for i in range(3):
        assert len({names[i] for names in CATCH22_NAMES}) == 22


@pytest.mark.parametrize("short_name, full_name, legacy_name", CATCH22_NAMES)
def test_catch22_names_select_matching_feature(short_name, full_name, legacy_name):
    """Test that the short, full and catch22 v0.x names select the same feature."""
    X = make_example_3d_numpy(
        n_cases=4, n_channels=1, n_timepoints=50, random_state=0, return_y=False
    )
    expected = Catch22(features=full_name).fit_transform(X)
    testing.assert_array_equal(Catch22(features=short_name).fit_transform(X), expected)
    if legacy_name == full_name:
        return
    with pytest.warns(FutureWarning, match="catch22 v0.x feature names"):
        c22 = Catch22(features=[legacy_name])
    testing.assert_array_equal(c22.fit_transform(X), expected)


def test_catch22_legacy_short_names_warn():
    """Test that the catch22 v0.x short names select their features with a warning."""
    X = make_example_3d_numpy(
        n_cases=4, n_channels=1, n_timepoints=50, random_state=0, return_y=False
    )
    with pytest.warns(FutureWarning, match="catch22 v0.x feature names"):
        c22 = Catch22(features=["transition_matrix", "centroid_freq"])
    testing.assert_array_equal(
        c22.fit_transform(X),
        Catch22(features=["transition_variance", "median_freq"]).fit_transform(X),
    )


def _reference_series():
    """Return z-normalised series for the catch22 v1.0 reference values."""
    rng = np.random.default_rng(0)
    ar = np.zeros(200)
    for i in range(1, 200):
        ar[i] = 0.8 * ar[i - 1] + rng.standard_normal()
    logistic = np.zeros(100)
    logistic[0] = 0.3
    for i in range(1, 100):
        logistic[i] = 3.9 * logistic[i - 1] * (1 - logistic[i - 1])
    series = [
        rng.standard_normal(300),
        np.cumsum(rng.standard_normal(300)),
        np.sin(2 * np.pi * np.arange(128) / 20) + 0.1 * rng.standard_normal(128),
        ar,
        logistic,
        rng.standard_normal(50),
    ]
    return [(s - s.mean()) / s.std(ddof=1) for s in series]


def test_catch22_matches_catch22_v1_reference():
    """Test Catch22 against catch22 v1.0 on z-normalised series.

    The reference values are from pycatch22 1.0.2 (catch22 v1.1.0 C code, the
    same values as v1.0), whose features are all computed on z-normalised series.
    The last series is too short for the fluctuation analysis features, which are
    masked.
    """
    series = _reference_series()
    Xt = Catch22().fit_transform([s.reshape(1, -1) for s in series])
    testing.assert_allclose(Xt, catch22_v1_reference, rtol=1e-6, atol=1e-9)


def test_catch22_masks_constant_series():
    """Test the values of features that cannot be estimated, as in catch22 v1.0."""
    X = np.full((2, 1, 30), 2.5)
    Xt = Catch22(catch24=True).fit_transform(X)
    testing.assert_allclose(Xt[0, :22], catch22_v1_constant_mask, rtol=1e-12)
    testing.assert_array_equal(Xt[:, 22:], [[2.5, 0.0], [2.5, 0.0]])
    Xt = Catch22(mask_nans=False).fit_transform(X)
    assert np.isnan(Xt).all()


